package app

import (
	"flag"
	"fmt"
	"strings"

	"github.com/sharon-xa/pretty-alias/v2/internal/shell"
)

// flagSpec is what a completion script needs to know about one flag.
type flagSpec struct {
	name   string
	desc   string
	isBool bool     // takes no value
	values []string // fixed set of values; nil means free text
	file   bool     // value is a path
}

// flagSpecs describes every flag in fs (plus --help), so the completion
// scripts can't drift from the real flags. values holds the fixed values of
// flags that have them, and fileFlag names the flag that takes a path.
func flagSpecs(fs *flag.FlagSet, values map[string][]string, fileFlag string) []flagSpec {
	var specs []flagSpec
	fs.VisitAll(func(f *flag.Flag) {
		b, ok := f.Value.(interface{ IsBoolFlag() bool })
		specs = append(specs, flagSpec{
			name:   f.Name,
			desc:   shortDesc(f.Usage),
			isBool: ok && b.IsBoolFlag(),
			values: values[f.Name],
			file:   f.Name == fileFlag,
		})
	})
	return append(specs, flagSpec{name: "help", desc: "show help and exit", isBool: true})
}

// shortDesc keeps the part of a flag's usage text before any details.
func shortDesc(usage string) string {
	for _, sep := range []string{"\n", ": ", " (", ";"} {
		usage, _, _ = strings.Cut(usage, sep)
	}
	return strings.TrimSpace(usage)
}

// completionScript returns a completion script for sh covering specs.
func completionScript(sh shell.Shell, specs []flagSpec) string {
	switch sh {
	case shell.Zsh:
		return zshCompletion(specs)
	case shell.Fish:
		return fishCompletion(specs)
	default:
		return bashCompletion(specs)
	}
}

func bashCompletion(specs []flagSpec) string {
	var b strings.Builder
	b.WriteString(`# bash completion for pretty-alias. Generated by: pretty-alias --completion bash
_pretty_alias() {
    local cur=${COMP_WORDS[COMP_CWORD]} prev=${COMP_WORDS[COMP_CWORD-1]}
    # bash splits "--flag=value" at the "=".
    if [[ $cur == = ]]; then
        cur=
    elif [[ $prev == = ]]; then
        prev=${COMP_WORDS[COMP_CWORD-2]}
    fi
    case $prev in
`)
	var all []string
	for _, s := range specs {
		all = append(all, "--"+s.name)
		switch {
		case s.file:
			fmt.Fprintf(&b, "        --%s | -%s)\n", s.name, s.name)
			b.WriteString("            compopt -o filenames 2>/dev/null\n")
			b.WriteString("            local IFS=$'\\n'\n")
			b.WriteString("            COMPREPLY=($(compgen -f -- \"$cur\"))\n")
			b.WriteString("            return ;;\n")
		case s.values != nil:
			fmt.Fprintf(&b, "        --%s | -%s)\n", s.name, s.name)
			fmt.Fprintf(&b, "            COMPREPLY=($(compgen -W %s -- \"$cur\"))\n",
				shQuote(strings.Join(s.values, " ")))
			b.WriteString("            return ;;\n")
		case !s.isBool:
			fmt.Fprintf(&b, "        --%s | -%s) return ;;\n", s.name, s.name)
		}
	}
	b.WriteString("    esac\n")
	fmt.Fprintf(
		&b,
		"    COMPREPLY=($(compgen -W %s -- \"$cur\"))\n",
		shQuote(strings.Join(all, " ")),
	)
	b.WriteString("}\ncomplete -F _pretty_alias pretty-alias\n")
	return b.String()
}

func zshCompletion(specs []flagSpec) string {
	var b strings.Builder
	b.WriteString(`#compdef pretty-alias
# zsh completion for pretty-alias. Generated by: pretty-alias --completion zsh
_pretty-alias() {
    _arguments \
`)
	for _, s := range specs {
		desc := zshEscape(s.desc)
		var spec string
		switch {
		case s.isBool:
			spec = fmt.Sprintf("--%s[%s]", s.name, desc)
		case s.file:
			spec = fmt.Sprintf("--%s=[%s]:%s:_files", s.name, desc, s.name)
		case s.values != nil:
			spec = fmt.Sprintf("--%s=[%s]:%s:(%s)", s.name, desc, s.name,
				strings.Join(s.values, " "))
		default:
			spec = fmt.Sprintf("--%s=[%s]:%s: ", s.name, desc, s.name)
		}
		fmt.Fprintf(&b, "        %s \\\n", shQuote(spec))
	}
	b.WriteString(`        && return 0
}
# Works both from a file in $fpath and when sourced.
if [[ ${zsh_eval_context[-1]} == loadautofunc ]]; then
    _pretty-alias "$@"
else
    compdef _pretty-alias pretty-alias
fi
`)
	return b.String()
}

func fishCompletion(specs []flagSpec) string {
	var b strings.Builder
	b.WriteString(
		"# fish completion for pretty-alias. Generated by: pretty-alias --completion fish\n",
	)
	b.WriteString("complete -c pretty-alias -f\n")
	for _, s := range specs {
		fmt.Fprintf(&b, "complete -c pretty-alias -l %s", s.name)
		switch {
		case s.file:
			b.WriteString(" -r -F")
		case s.values != nil:
			fmt.Fprintf(&b, " -x -a %s", fishQuote(strings.Join(s.values, " ")))
		case !s.isBool:
			b.WriteString(" -x")
		}
		fmt.Fprintf(&b, " -d %s\n", fishQuote(s.desc))
	}
	return b.String()
}

// shQuote single-quotes s for bash and zsh.
func shQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// fishQuote single-quotes s for fish, where \ and ' are escaped with \.
func fishQuote(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

// zshEscape escapes the characters _arguments treats specially inside [...].
func zshEscape(s string) string {
	return strings.NewReplacer(`\`, `\\`, `[`, `\[`, `]`, `\]`, `:`, `\:`).Replace(s)
}
